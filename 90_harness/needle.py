#!/usr/bin/env python3
"""Стог с иголкой: печатает промпт, в котором на заданной относительной глубине спрятан код.

Восстановлено по интерфейсу серверного скрипта, чтобы стенд точности не зависел от инстанса.
Использование: needle.py <глубина 0..1> <предложений> <seed>

При 900 предложениях промпт весит примерно 60 КБ ≈ 15 тыс. токенов, поэтому CLI надо запускать
с `--max-context 32768`: при меньшем контексте он отвергает аргументы и печатает подсказку по
флагам вместо ответа, а тест молча показывает 0/5.
"""
import random
import sys

NEEDLE = '8317-KQ'
FILLER = [
    'Городская библиотека закрывается по вторникам в семь часов вечера.',
    'Осенью на набережной ветер меняет направление ближе к полудню.',
    'Старый мост перекрашивали дважды: сначала в серый, потом в зелёный.',
    'В пекарне на углу тесто ставят в четыре утра и не раньше.',
    'Трамвайные пути на площади заменили за одно лето.',
    'Смотритель маяка вёл журнал наблюдений тридцать два года подряд.',
    'Первые заморозки в этих местах приходят в середине октября.',
    'На чердаке хранились подшивки газет за четырнадцать лет.',
    'Паром ходит через пролив каждые сорок минут, кроме штормовых дней.',
    'Часовщик принимал заказы только по предварительной записи.',
]


def main():
    depth = float(sys.argv[1]) if len(sys.argv) > 1 else 0.5
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 900
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 7
    rng = random.Random(seed)

    lines = [rng.choice(FILLER) for _ in range(count)]
    at = min(count - 1, max(0, int(round(depth * (count - 1)))))
    lines[at] = f'Служебный код доступа к архиву — {NEEDLE}. Запомните его.'

    print('Ниже приведён длинный текст. Прочитайте его и ответьте на вопрос в конце.\n')
    print(' '.join(lines))
    print('\nВопрос: какой служебный код доступа к архиву упомянут в тексте? '
          'Ответьте только кодом, без пояснений.')


main()
